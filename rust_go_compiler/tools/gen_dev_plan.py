def impl_ms(rec: dict) -> str:
    kind = rec.get("kind", "")
    name = rec.get("name", "")
    if kind == "pragma":
        base = name.replace("//go:", "")
        if base == "build":
            return "M2"
        if base == "embed":
            return "M5"
        if base in ("linkname", "linknamestd"):
            return "M5"
        if base in ("noescape", "uintptrescapes", "uintptr", "uintptrkeepalive"):
            return "M7"
        if base == "noinline":
            return "M7"
        if base == "nointerface":
            return "M2"
        if base.startswith("cgo"):
            return "M5"
        if base in ("wasmimport", "wasmexport"):
            return "M7.2-T3"
        if base == "generate":
            return "M0"
        return "M5"
    if kind == "flag":
        if name == "Lang":
            return "M0"
        return "M7"  # all other flags = compiler driver / infra
    if kind == "rules":
        if name in ("generic.rules", "dec.rules", "dec64.rules",
                     "divisible.rules", "divmod.rules"):
            return "M7"
        if name.startswith("AMD64") or name == "simdAMD64.rules":
            return "M7.2-T1"
        if name.startswith("ARM64") or name == "simdARM64.rules":
            return "M7.2-T2"
        return "M7.2-T3"
    if kind == "obj":
        arch = rec.get("arch", "")
        if arch == "x86":
            return "M7.2-T1"
        if arch == "arm64":
            return "M7.2-T2"
        return "M7.2-T3"
    return "M?"


def test_ms(rec: dict) -> str:
    tid = rec.get("test_id", "")
    parts = tid.split(":")
    layer = parts[0] if parts else ""

    # L5: script tests — only 2 parts ("L5:filename.txt"), no directory.
    # Must check before the len < 3 guard.
    if layer == "L5":
        return "M5"

    if len(parts) < 3:
        return "M?"

    d = parts[1]

    # Root dir (test/*.go) — mixed across all front-end milestones.
    if d in ("", "."):
        return "M0-M5"
    # Backend / codegen
    if d == "codegen":
        return "M7"
    if d == "escape":
        return "M7"
    if d == "abi":
        return "M7"
    if d == "dwarf":
        return "M7"
    if d == "simd":
        return "M7.2-T1"
    # Generics
    if d.startswith("typeparam"):
        return "M2"
    # Front-end by topic
    if d == "syntax":
        return "M0"
    if d == "typeswitch":
        return "M3"
    if d in ("iface", "interface"):
        return "M2"
    if d == "typecheck":
        return "M2"
    if d == "chan":
        return "M4"
    if d == "ken":
        return "M0-M5"  # Ken Thompson's suite — mixed
    if d == "arenas":
        return "M5"
    # Runtime/internal
    if d.startswith("internal"):
        return "M6"
    # Regression — actually needs per-file triage
    if d == "fixedbugs":
        return "M6"
    return f"M? ({d})"


