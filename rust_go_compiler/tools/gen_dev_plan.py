def main() -> int:
    cov = COVERAGE_DIR
    specs = load_toml(cov / "spec_atoms.toml").get("spec_atoms", [])
    impls = load_toml(cov / "impl_atoms.toml").get("impl_atoms", [])
    tests = load_toml(cov / "official-tests.toml").get("test_atoms", [])
    feats = load_toml(cov / "features.toml").get("features", [])

    # Compute claimed atom IDs from features.toml
    claimed: set[str] = set()
    for f in feats:
        claimed.update(f.get("spec_atoms", []))
        claimed.update(f.get("impl_atoms", []))
        claimed.update(f.get("test_ids", []))
        claimed.update(f.get("negative_test_ids", []))

    # Assign milestones
    spec_ms = {r["atom_id"]: SPEC_MS.get(r["atom_id"].replace("spec:", ""), "M?") for r in specs}
    impl_ms_map = {r["atom_id"]: impl_ms(r) for r in impls}
    test_ms_map = {r["test_id"]: test_ms(r) for r in tests}

    # Group by milestone
    ms: dict[str, dict] = defaultdict(lambda: {
        "specs": [], "impls": [], "tests": [],
        "spec_c": 0, "spec_u": 0,
        "impl_c": 0, "impl_u": 0,
        "test_c": 0, "test_u": 0,
    })

    for r in specs:
        m = spec_ms[r["atom_id"]]
        ms[m]["specs"].append(r)
        if r["atom_id"] in claimed:
            ms[m]["spec_c"] += 1
        else:
            ms[m]["spec_u"] += 1

    for r in impls:
        m = impl_ms_map[r["atom_id"]]
        ms[m]["impls"].append(r)
        if r["atom_id"] in claimed:
            ms[m]["impl_c"] += 1
        else:
            ms[m]["impl_u"] += 1

    for r in tests:
        m = test_ms_map[r["test_id"]]
        ms[m]["tests"].append(r)
        if r["test_id"] in claimed:
            ms[m]["test_c"] += 1
        else:
            ms[m]["test_u"] += 1

    # ── Generate markdown ──────────────────────────────────────────────
    L: list[str] = []
    L.append("# 候选开发计划（auto-clustered from A/B/C）")
    L.append("")
    L.append("> ⚠️ **这是候选骨架，不是已验证的计划。**")
    L.append("> 每个 atom 的里程碑归属是按关键词自动分配的，未经人工审核。")
    L.append("> 要变成「零遗漏」计划，需要：")
    L.append("> 1. 人工审核每个 atom 的里程碑归属")
    L.append("> 2. 填充 `features.toml`（每条 feature 给出 A/B/C 三侧锚点 + 里程碑 + target_dim）")
    L.append("> 3. 实现闸三（变异注入差分）和闸四（负测试差分）")
    L.append("> 4. 写一个能通过测试的 Rust 编译器")
    L.append("")
    L.append(f"> 基线：go1.27.1  |  A(spec)={len(specs)}  B(impl)={len(impls)}  C(test)={len(tests)}  "
             f"features={len(feats)}  claimed={len(claimed)}")
    L.append("")

    # ── Summary table ──────────────────────────────────────────────────
    L.append("## 里程碑总览")
    L.append("")
    L.append("| 里程碑 | 主题 | spec | impl | test | 已认领 | 未认领 |")
    L.append("|---|---|---:|---:|---:|---:|---:|")
    for m in MILESTONE_ORDER:
        if m not in ms:
            continue
        d = ms[m]
        total = len(d["specs"]) + len(d["impls"]) + len(d["tests"])
        if total == 0:
            continue
        claimed_n = d["spec_c"] + d["impl_c"] + d["test_c"]
        unclaimed = total - claimed_n
        title = MS_TITLE.get(m, m)
        L.append(f"| {m} | {title.split(': ', 1)[-1]} "
                 f"| {len(d['specs'])} | {len(d['impls'])} | {len(d['tests'])} "
                 f"| {claimed_n} | {unclaimed} |")
    L.append("")

    # ── Per-milestone detail ──────────────────────────────────────────
    L.append("## 逐里程碑明细")
    L.append("")
    for m in MILESTONE_ORDER:
        if m not in ms:
            continue
        d = ms[m]
        total = len(d["specs"]) + len(d["impls"]) + len(d["tests"])
        if total == 0:
            continue
        title = MS_TITLE.get(m, m)
        L.append(f"### {title}")
        L.append("")

        # Spec atoms
        if d["specs"]:
            L.append(f"**spec 条款 ({len(d['specs'])})**")
            L.append("")
            for r in d["specs"]:
                aid = r["atom_id"]
                mark = "✓" if aid in claimed else "○"
                L.append(f"- {mark} `{aid}` — {r.get('title', '')}")
            L.append("")

        # Impl atoms
        if d["impls"]:
            L.append(f"**impl 原子 ({len(d['impls'])})**")
            L.append("")
            # Group by kind
            by_kind: dict[str, list] = defaultdict(list)
            for r in d["impls"]:
                by_kind[r.get("kind", "?")].append(r)
            for kind in ("pragma", "flag", "rules", "obj"):
                if kind not in by_kind:
                    continue
                recs = by_kind[kind]
                L.append(f"- {kind} ({len(recs)}):")
                for r in recs:
                    aid = r["atom_id"]
                    mark = "✓" if aid in claimed else "○"
                    extra = ""
                    if "pass" in r:
                        extra = f" [pass={r['pass']}, rules={r.get('rule_count', '?')}]"
                    elif "arch" in r:
                        extra = f" [arch={r['arch']}, loc={r.get('loc', '?')}]"
                    elif "help" in r:
                        extra = f" — {r['help'][:60]}"
                    L.append(f"  - {mark} `{aid}`{extra}")
            L.append("")

        # Test atoms
        if d["tests"]:
            L.append(f"**测试 ({len(d['tests'])})**")
            L.append("")
            # Group by sub-directory
            by_dir: dict[str, list] = defaultdict(list)
            for r in d["tests"]:
                parts = r["test_id"].split(":")
                subdir = parts[1] if len(parts) > 1 else "?"
                by_dir[subdir].append(r)
            for subdir in sorted(by_dir.keys()):
                recs = by_dir[subdir]
                claimed_n = sum(1 for r in recs if r["test_id"] in claimed)
                label = subdir if subdir else "(root)"
                L.append(f"- `L?:{label}` — {len(recs)} 个（已认领 {claimed_n}）")
            L.append("")

        # Candidate feature_ids (empty — to be filled)
        unclaimed = (d["spec_u"] + d["impl_u"] + d["test_u"])
        if unclaimed > 0:
            L.append(f"*候选 feature_ids：{unclaimed} 个未认领 atom 待归属（人工填写 `features.toml`）*")
            L.append("")

    # ── Current attribution ──────────────────────────────────────────
    L.append("## 当前认领状态（features.toml）")
    L.append("")
    if not feats:
        L.append("*(空)*")
    else:
        L.append("| feature_id | 里程碑 | target | status | spec | impl | test | neg | mut |")
        L.append("|---|---|---|---|---:|---:|---:|---:|:---:|")
        for f in feats:
            has_mut = "✓" if f.get("mutation_case_id") else "✗"
            L.append(f"| `{f['feature_id']}` | {f.get('main_task', '?')} "
                     f"| {f.get('target_dim', '?')} | {f.get('status', '?')} "
                     f"| {len(f.get('spec_atoms', []))} | {len(f.get('impl_atoms', []))} "
                     f"| {len(f.get('test_ids', []))} | {len(f.get('negative_test_ids', []))} "
                     f"| {has_mut} |")
    L.append("")

    # ── Gap analysis ──────────────────────────────────────────────────
    total_atoms = len(specs) + len(impls) + len(tests)
    total_unclaimed = total_atoms - len(claimed)
    L.append("## 缺口分析（到「已验证计划」还差什么）")
    L.append("")
    L.append(f"| 项 | 状态 |")
    L.append(f"|---|---|")
    L.append(f"| 闸一：机械生成三集 | ✅ 已实现（A={len(specs)}, B={len(impls)}, C={len(tests)}）|")
    L.append(f"| 闸二：三角 diff | ✅ 已实现（`triangle_diff.py`，{total_unclaimed} 个未认领）|")
    L.append(f"| 闸三：变异注入差分 | ❌ 未实现（需写 harness：故意改 reference 一个行为，验证 harness 能抓到）|")
    L.append(f"| 闸四：负测试差分 | ❌ 未实现（需写 harness：reference 拒绝的代码 Rust 也必须拒绝）|")
    L.append(f"| features.toml 归属 | ⏳ {len(feats)} 条（需人工填写到覆盖全部 atom）|")
    L.append(f"| Rust 编译器 | ❌ 不存在（`nobody0726/go-compiler-rust` 有 13 个 crate 骨架）|")
    L.append("")
    L.append("**下一步建议**：")
    L.append(f"1. 从 M0（词法）开始逐条人工审核本骨架的 spec 归属，填写 `features.toml`")
    L.append(f"2. 对 M0 的每条 spec clause，找到对应的 B 集 impl atom（pragma/flag/包）和 C 集测试")
    L.append(f"3. 用 `validate_features.py` 校验每条 feature 四道闸（静态半边）")
    L.append(f"4. 扩 B 集加导出符号（当前只有 pragma/flag/rules/obj，缺 `defer`/`range` 改写等纯源码实现）")
    L.append("")

    md = "\n".join(L)
    out = cov / "dev-plan-candidate.md"
    out.write_text(md, encoding="utf-8")
    print(f"wrote {out} ({len(md)} bytes, {len(L)} lines)")
    print(f"milestones with atoms: {len([m for m in MILESTONE_ORDER if m in ms and sum(len(ms[m][k]) for k in ('specs','impls','tests')) > 0])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
